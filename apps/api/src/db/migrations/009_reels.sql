CREATE TABLE IF NOT EXISTS reels (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  author_id BIGINT UNSIGNED NOT NULL,
  video_url VARCHAR(500) NOT NULL,
  caption VARCHAR(500) NULL,
  views_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMP NULL,
  INDEX idx_reels_author (author_id, created_at),
  INDEX idx_reels_created (created_at),
  CONSTRAINT fk_rl_user FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS reel_likes (
  reel_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (reel_id, user_id),
  CONSTRAINT fk_rlk_reel FOREIGN KEY (reel_id) REFERENCES reels(id) ON DELETE CASCADE,
  CONSTRAINT fk_rlk_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
